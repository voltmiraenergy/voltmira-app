// scripts/build-md-grid.mjs — Moldova's high-voltage grid from OpenStreetMap,
// kept in the app as lib/data/mdGridOsm.js so a plant's grid lookup
// (lib/gridData.js fetchGridNear) answers at once and does not depend on the
// public Overpass servers, which are often too busy to answer a query this
// size. Substations of 35 kV and above and transmission substations inside
// Moldova; high-voltage lines in a box around it (a site near the border can
// connect across it); towns and villages, to name an unnamed point. Line
// routes are simplified to about 25 m and every coordinate cut to 5 decimals.
//
//   node scripts/build-md-grid.mjs
//
// Data: © OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).
// Credited where the grid is shown and on /credits. Run again to refresh.
import fs from "node:fs";

const SERVERS = [
  "https://overpass-api.de/api/interpreter",
  "https://overpass.private.coffee/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter",
];
const KV = "(35|110|150|220|330|400|750)000";
const BOX = "45.2,26.3,48.7,30.5"; // Moldova and about 25 km around it
const QUERY = `[out:json][timeout:240][maxsize:536870912];
area["ISO3166-1"="MD"][admin_level=2]->.md;
(
  nwr["power"="substation"]["voltage"~"${KV}"](area.md);
  nwr["power"="substation"]["substation"="transmission"](area.md);
);
out tags center qt;
way["power"="line"]["voltage"~"${KV}"](${BOX});
out tags geom qt;
node["place"~"^(city|town|village)$"](area.md);
out qt;`;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const r5 = (x) => Math.round(x * 1e5) / 1e5;
const KEEP_TAGS = ["power", "voltage", "substation", "name", "name:ro", "operator", "place"];

async function fetchOnce(url) {
  const res = await fetch(url, {
    method: "POST", body: "data=" + encodeURIComponent(QUERY),
    headers: { "content-type": "application/x-www-form-urlencoded", "user-agent": "VoltMira/1.0 (grid dataset build; hello@voltmira.com)" },
    signal: AbortSignal.timeout(300000),
  });
  if (!res.ok) throw new Error(`${url} ${res.status}`);
  const json = await res.json();
  if (!Array.isArray(json.elements) || json.elements.length < 100) throw new Error(`${url} too few elements (${json.elements?.length})`);
  return json;
}

// Douglas-Peucker on [lat, lon], tolerance in degrees (about 25 m)
function simplify(pts, tol = 0.00025) {
  if (pts.length <= 2) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ay, ax] = pts[a], [by, bx] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-12;
    let far = -1, fd = 0;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * (pts[i][1] - ax) - dx * (pts[i][0] - ay)) / len;
      if (d > fd) { fd = d; far = i; }
    }
    if (far > 0 && fd > tol) { keep[far] = 1; stack.push([a, far], [far, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

let json = null;
for (let round = 0; round < 6 && !json; round++) {
  for (const url of SERVERS) {
    try { console.log("asking", url); json = await fetchOnce(url); console.log("got", json.elements.length, "elements from", url); break; }
    catch (e) { console.log("  failed:", e.message); }
  }
  if (!json) { console.log(`all busy, waiting ${30 * (round + 1)} s`); await sleep(30000 * (round + 1)); }
}
if (!json) { console.error("no server answered; try again later"); process.exit(1); }

const tags = (t = {}) => Object.fromEntries(KEEP_TAGS.filter((k) => t[k] != null).map((k) => [k, String(t[k]).slice(0, 120)]));
const out = [];
for (const e of json.elements) {
  const t = e.tags || {};
  if (t.power === "substation") {
    const c = e.center || (e.lat != null ? { lat: e.lat, lon: e.lon } : null);
    if (c) out.push({ type: e.type, id: e.id, tags: tags(t), center: { lat: r5(c.lat), lon: r5(c.lon) } });
  } else if (t.power === "line" && Array.isArray(e.geometry)) {
    const g = simplify(e.geometry.filter(Boolean).map((p) => [r5(p.lat), r5(p.lon)]));
    if (g.length >= 2) out.push({ type: "way", id: e.id, tags: tags(t), geometry: g.map(([lat, lon]) => ({ lat, lon })) });
  } else if (t.place && e.lat != null) {
    out.push({ type: "node", id: e.id, tags: tags(t), lat: r5(e.lat), lon: r5(e.lon) });
  }
}
const counts = out.reduce((m, e) => { const k = e.tags.power || "place"; m[k] = (m[k] || 0) + 1; return m; }, {});
const stamp = String(json.osm3s?.timestamp_osm_base || new Date().toISOString()).slice(0, 10);
const body = `// lib/data/mdGridOsm.js — GENERATED by scripts/build-md-grid.mjs; do not edit.
// Moldova's high-voltage grid (substations of 35 kV and above, lines around
// the country) and its towns and villages, from OpenStreetMap as of ${stamp}.
// © OpenStreetMap contributors, ODbL 1.0, https://www.openstreetmap.org/copyright
// Server only: read by lib/gridData.js.
export const MD_GRID_AS_OF = ${JSON.stringify(stamp)};
export const MD_GRID_COUNTS = ${JSON.stringify(counts)};
export const MD_GRID_ELEMENTS = ${JSON.stringify(out)};
`;
fs.writeFileSync(new URL("../lib/data/mdGridOsm.js", import.meta.url), body);
console.log("wrote lib/data/mdGridOsm.js", counts, Math.round(body.length / 1024), "kB");
