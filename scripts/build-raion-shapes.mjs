// scripts/build-raion-shapes.mjs — turn the geoBoundaries ADM1 file for Moldova
// into lib/data/mdRaionShapes.js: one feature per area keyed by our raion id
// (lib/mdRaions.js), coordinates cut to 4 decimals (about 10 m, plenty for a
// district map), and each area's centre for labels and "nearby" lists.
//
//   node scripts/build-raion-shapes.mjs path/to/geoBoundaries-MDA-ADM1_simplified.geojson
//
// Source: geoBoundaries gbOpen MDA ADM1 (UNHCR, OCHA FISS), CC BY 3.0 IGO,
// https://www.geoboundaries.org. Credited on /credits.
import fs from "node:fs";
import { raionId, RAIONS } from "../lib/mdRaions.js";

const src = process.argv[2];
if (!src) { console.error("usage: node scripts/build-raion-shapes.mjs <geojson>"); process.exit(1); }
const g = JSON.parse(fs.readFileSync(src, "utf8"));
const r4 = (x) => Math.round(x * 1e4) / 1e4;
const roundRing = (ring) => ring.map(([x, y]) => [r4(x), r4(y)]).filter((p, i, a) => i === 0 || p[0] !== a[i - 1][0] || p[1] !== a[i - 1][1]);

// the centre of an outline: the area-weighted centroid of its largest polygon
function centre(polys) {
  let best = null, bestA = -1;
  for (const p of polys) {
    const ring = p[0]; let a = 0, cx = 0, cy = 0;
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const f = ring[j][0] * ring[i][1] - ring[i][0] * ring[j][1];
      a += f; cx += (ring[j][0] + ring[i][0]) * f; cy += (ring[j][1] + ring[i][1]) * f;
    }
    if (Math.abs(a) > bestA) { bestA = Math.abs(a); best = [r4(cy / (3 * a)), r4(cx / (3 * a))]; }
  }
  return best; // [lat, lon]
}

const features = [], centres = {};
for (const f of g.features) {
  const id = raionId(f.properties.shapeName);
  if (!id) throw new Error("unknown area " + f.properties.shapeName);
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rounded = polys.map((p) => p.map(roundRing));
  features.push({ type: "Feature", properties: { id }, geometry: { type: "MultiPolygon", coordinates: rounded } });
  centres[id] = centre(rounded);
}
const missing = RAIONS.filter((r) => !centres[r.id]).map((r) => r.id);
if (missing.length) throw new Error("no outline for " + missing.join(", "));

const out = `// lib/data/mdRaionShapes.js — GENERATED by scripts/build-raion-shapes.mjs; do not edit.
// Moldova's first-level areas, keyed by lib/mdRaions.js ids. Source: geoBoundaries
// gbOpen MDA ADM1 (UNHCR, OCHA FISS), CC BY 3.0 IGO, https://www.geoboundaries.org
export const SHAPES_SOURCE = { name: "geoBoundaries", authors: "UNHCR, OCHA FISS", license: "CC BY 3.0 IGO", url: "https://www.geoboundaries.org" };
export const CENTRES = ${JSON.stringify(centres)};
export const SHAPES = ${JSON.stringify({ type: "FeatureCollection", features })};
`;
fs.writeFileSync(new URL("../lib/data/mdRaionShapes.js", import.meta.url), out);
console.log("wrote lib/data/mdRaionShapes.js", features.length, "areas", Math.round(out.length / 1024), "kB");
