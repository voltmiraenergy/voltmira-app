export const PT = T;

/** Where a study's figures come from, for a document: "DNV, 2026-05-01, page 23"; empty when nothing is recorded. */
export function studyCite(study, lang = "en") {
  if (!study) return "";
  const parts = [study.by, study.date].filter(Boolean);
  if (study.pages?.p50) parts.push(plt("rd_page", lang, { p: study.pages.p50 }));
  return parts.join(", ");
}

/** The P90 horizon the studies' figures are for, when every study of the plant states the same one. */
export function p90BasisNote(plant, lang = "en") {
  const bases = [plant?.wind?.study, plant?.solar?.study].filter((s) => s && s.p50Mwh > 0).map((s) => s.p90Basis || "");
  return bases.length && bases.every((b) => b && b === bases[0]) ? plt("p90_basis_" + bases[0], lang) : "";
}

export function plt(key, lang = "en", vars = null) {
  const e = (vars && Number(vars.n) === 1 && T[key + "_one"]) || T[key];
  let s = e ? (e[lang] ?? e.en) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v ?? ""));
  return s;
}
